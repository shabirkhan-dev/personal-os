// Writes src/lib/photos/bundled-photos.ts: a static require() for every built-in photo in
// app-photos/, so they ship inside the app (Metro needs literal paths). Run after adding one:
//   node scripts/gen-bundled-photos.mjs
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const source = join(root, "app-photos");
const files = [];
const walk = (dir) => {
	for (const name of readdirSync(dir).toSorted()) {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) walk(path);
		else if (/\.(webp|png|jpe?g)$/.test(name)) files.push(relative(source, path));
	}
};
walk(source);

const lines = files.map((file) => `\t"${file}": require("../../../app-photos/${file}"),`);
writeFileSync(
	join(root, "src/lib/photos/bundled-photos.ts"),
	`// Generated by scripts/gen-bundled-photos.mjs; do not edit by hand.
/* oxlint-disable */
import type { ImageSourcePropType } from "react-native";

/** Every built-in photo (app-photos/), bundled with the app so it shows offline and without R2. */
export const BUNDLED_PHOTOS: Record<string, ImageSourcePropType> = {
${lines.join("\n")}
};
`,
);
console.log(`bundled ${files.length} photos`);
