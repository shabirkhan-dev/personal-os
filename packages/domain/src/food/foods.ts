import type { Macros } from "./model";

/**
 * Everyday foods, mostly Pakistani home food, with the macros of one usual portion. Values are
 * rounded estimates from standard nutrition tables, close enough for a daily log; the person can
 * adjust any item. Prices are rough Rupee costs of one portion's ingredients, used for the meal
 * plan's cost line, never for anything that matters to money.
 */
export type Food = Macros & {
	id: string;
	name: string;
	/** Words people say for it, matched longest first. */
	names: readonly string[];
	/** The portion: "" (one piece), "cup", "plate", "bowl", "glass", "slice", "tbsp", "scoop". */
	unit: string;
	/** Rupees for one portion. */
	price: number;
};

