export function foodById(id: string): Food | undefined {
	return FOODS.find((item) => item.id === id);
}

/** Every alias, longest first, so "chai with milk" wins over "milk" and "fried eggs" over "eggs". */
export const ALIASES: readonly { alias: string; food: Food }[] = FOODS.flatMap((item) =>
	item.names.map((alias) => ({ alias, food: item })),
).sort((a, b) => b.alias.length - a.alias.length);
